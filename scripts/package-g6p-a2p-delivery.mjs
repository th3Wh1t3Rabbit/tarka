#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { execFileSync, spawnSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, utimesSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repository = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const archiveName = 'TRACE_ESCAPE_G6P_A2P_PLACEHOLDER_SAFE_NARRATIVE_AND_MISSION_SYSTEMS_DELIVERY_v1.0.0.zip'
const output = path.resolve(repository, '..', archiveName)
const temporary = mkdtempSync(path.join(os.tmpdir(), 'trace-g6p-a2p-'))
const deliveryRoot = path.join(temporary, archiveName.replace(/\.zip$/, ''))
const git = (...args) => execFileSync('git', args, { cwd: repository, encoding: 'utf8' }).trim()
const run = (command, args, cwd = repository) => { const result = spawnSync(command, args, { cwd, encoding: 'utf8' }); if (result.status !== 0) throw new Error(`${command} failed: ${result.stderr || result.stdout}`); return (result.stdout ?? '').trim() }
const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')
const filesBelow = (root) => readdirSync(root, { withFileTypes: true }).flatMap((entry) => { const target = path.join(root, entry.name); return entry.isDirectory() ? filesBelow(target) : [target] })

try {
  // Recreate all verification logs and the production preview immediately
  // before staging so mutable generated bytes are bound to this package run.
  run('npm', ['run', 'g6p:a2p:verify'])
  const verificationFile = path.join(repository, 'artifacts/g6p-a2p/verification/FINAL_VERIFICATION.json')
  if (!existsSync(verificationFile)) throw new Error('Run g6p:a2p:verify first')
  const verification = JSON.parse(readFileSync(verificationFile, 'utf8'))
  if (verification.result !== 'PASSED') throw new Error('Final verification did not pass')
  const head = git('rev-parse', 'HEAD')
  const tree = git('rev-parse', 'HEAD^{tree}')
  if (verification.candidateCommit !== head || verification.candidateTree !== tree) throw new Error('Verification identity does not exactly match packaged HEAD/tree')
  const deliveryInputs = ['src', 'tests', 'public', 'docs', 'scripts', 'package.json', 'artifacts/g6p-a2p/reviews']
  const dirtyDeliveryInputs = git('status', '--porcelain=v1', '--untracked-files=all', '--', ...deliveryInputs)
  if (dirtyDeliveryInputs) throw new Error(`Uncommitted delivery inputs:\n${dirtyDeliveryInputs}`)

  mkdirSync(path.join(deliveryRoot, 'SOURCE_SNAPSHOT'), { recursive: true })
  const sourceTar = path.join(temporary, 'source.tar')
  run('git', ['archive', '--format=tar', '-o', sourceTar, 'HEAD'])
  run('tar', ['-xf', sourceTar, '-C', path.join(deliveryRoot, 'SOURCE_SNAPSHOT')])
  cpSync(path.join(repository, 'public/art-packs/placeholder'), path.join(deliveryRoot, 'PLACEHOLDER_PACK'), { recursive: true })
  cpSync(path.join(repository, 'public/art-packs/manifest.schema.json'), path.join(deliveryRoot, 'PLACEHOLDER_PACK/art-pack-v2.schema.json'))
  cpSync(path.join(repository, 'public/scenarios/euler-2023-false-exit'), path.join(deliveryRoot, 'ACCEPTED_EULER_SCENARIO'), { recursive: true })
  cpSync(path.join(repository, 'docs/G6P_A2P_SEMANTIC_RUNTIME.md'), path.join(deliveryRoot, 'SEMANTIC_RUNTIME.md'))
  cpSync(path.join(repository, 'docs/G6P_A2P_NARRATIVE_BEAT_MAP.md'), path.join(deliveryRoot, 'NARRATIVE_BEAT_MAP.md'))
  cpSync(path.join(repository, 'docs/G6P_A2P_MISSION_ROUTE_MAP.md'), path.join(deliveryRoot, 'MISSION_ROUTE_MAP.md'))
  cpSync(path.join(repository, 'artifacts/g6p-a2p'), path.join(deliveryRoot, 'EVIDENCE'), { recursive: true })
  cpSync(path.join(repository, 'dist'), path.join(deliveryRoot, 'PRINCIPAL_PREVIEW/site'), { recursive: true })
  writeFileSync(path.join(deliveryRoot, 'PRINCIPAL_PREVIEW/README.md'), '# Principal preview\n\nFrom this directory run `python3 -m http.server 8080 --directory site`, then open `http://127.0.0.1:8080/?mission=1`. This preview is provisional and makes no final-art or final-narrative claim.\n')

  mkdirSync(path.join(deliveryRoot, 'GIT'), { recursive: true })
  const bundle = path.join(deliveryRoot, 'GIT/trace-escape-complete.bundle')
  run('git', ['-c', 'pack.threads=1', 'bundle', 'create', bundle, '--all'])
  writeFileSync(path.join(deliveryRoot, 'GIT/BUNDLE_VERIFICATION.txt'), `${run('git', ['bundle', 'verify', bundle]).replaceAll(bundle, 'trace-escape-complete.bundle')}\n`)

  const manifest = {
    schemaVersion: '1.0.0', status: 'DELIVERED_PENDING_LEAD_REVIEW', archiveName,
    candidateCommit: head, parentCommit: git('rev-parse', 'HEAD^'), candidateTree: tree,
    reviewedBase: '8cb53c91e2dcaae81e9b84dfe848c19e27e96d9e', verifiedImplementationCommit: verification.candidateCommit,
    completeClonableGitBundle: true, sourceSnapshotIncluded: true, placeholderPackIncluded: true,
    semanticCatalogVersion: '1.0.0', artPackVersion: '2.0.0', historicalCutoffUtc: '2023-03-13T12:15:00Z',
    nansenRuntimeCalls: 0, alchemyRuntimeCalls: 0, credentialsAccessed: false,
    finalArtAcceptanceClaimed: false, finalNarrativeAcceptanceClaimed: false, fullEulerMissionAcceptanceClaimed: false, releaseAcceptanceClaimed: false,
  }
  writeFileSync(path.join(deliveryRoot, 'DELIVERY_MANIFEST.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  const prohibitedName = /(?:NANSEN_API_KEY|ALCHEMY_API_KEY|\.env(?:\.|$))/i
  for (const file of filesBelow(deliveryRoot)) {
    const relative = path.relative(deliveryRoot, file).replaceAll(path.sep, '/')
    if (prohibitedName.test(relative)) throw new Error(`Prohibited delivery file: ${relative}`)
    if (statSync(file).size < 5_000_000 && !/\.(?:png|webm|bundle)$/i.test(file)) {
      const content = readFileSync(file, 'utf8')
      if (/(?:^|\W)sk-[A-Za-z0-9_-]{16,}(?:$|\W)/.test(content)) throw new Error(`Credential-like material: ${relative}`)
    }
  }
  const preHashFiles = filesBelow(deliveryRoot)
  writeFileSync(path.join(deliveryRoot, 'DELIVERY_CONTENTS.sha256'), `${preHashFiles.map((file) => `${sha256(file)}  ${path.relative(deliveryRoot, file).replaceAll(path.sep, '/')}`).sort().join('\n')}\n`)
  const fixed = new Date('2000-01-01T00:00:00.000Z')
  const archiveFiles = filesBelow(deliveryRoot).sort()
  for (const file of archiveFiles) utimesSync(file, fixed, fixed)
  const entries = archiveFiles.map((file) => path.relative(temporary, file).replaceAll(path.sep, '/'))
  const second = path.join(temporary, 'reproducibility-check.zip')
  rmSync(output, { force: true })
  run('zip', ['-X', '-q', output, ...entries], temporary)
  run('zip', ['-X', '-q', second, ...entries], temporary)
  if (sha256(output) !== sha256(second)) throw new Error('Deterministic rebuild mismatch')
  run('unzip', ['-t', output])
  process.stdout.write(`${JSON.stringify({ status: manifest.status, archiveName, sha256: sha256(output), candidateCommit: head }, null, 2)}\n`)
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
